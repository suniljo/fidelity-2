
public class CharType {

	public static void main(String[] args) {
		char ch = 'A';
		System.out.println(ch);

		ch = 65; // implicit typecasting
		System.out.println(ch);
		
		ch = '\u0041';
		System.out.println(ch);
		
		ch = '\u0000'; //default value of char type
		System.out.println(ch);
	}

}
